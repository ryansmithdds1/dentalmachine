export function usePT() {
  const lang = useLang();
  return useCallback((s, vars) => {
    if (lang === 'es' && ES[s]) return vars ? ES[s].replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? '')) : ES[s];
    return translate(lang, s, vars);
  }, [lang]);
}
